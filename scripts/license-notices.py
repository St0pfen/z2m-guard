#!/usr/bin/env python3
"""Collect the licences of every crate that ends up in the shipped binary.

Two outputs from one `cargo metadata` run:

  THIRD-PARTY.md                  compact, committed — what ships and under which terms
  dist/THIRD-PARTY-LICENSES.txt   verbatim licence texts, bundled with the release

Binary distribution keeps MIT/BSD/ISC/Apache notices alive, so the licence text
of each crate has to travel with the artifact. Texts come from the local cargo
registry (offline, reproducible); crates that ship no licence file fall back to
the canonical text for their SPDX identifier, taken from this repo's own
LICENSE-MIT / LICENSE-APACHE.
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BIN = "z2m-guard"
TARGET = "x86_64-unknown-linux-musl"
OUT_MD = ROOT / "THIRD-PARTY.md"
OUT_TXT = ROOT / "dist" / "THIRD-PARTY-LICENSES.txt"

# Canonical texts we can reproduce from files already in the repo.
CANONICAL = {
    "MIT": ROOT / "LICENSE-MIT",
    "Apache-2.0": ROOT / "LICENSE-APACHE",
}


def metadata() -> dict:
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--all-features",
         "--filter-platform", TARGET],
        cwd=ROOT, capture_output=True, text=True, check=True,
    ).stdout
    return json.loads(out)


def reachable(meta: dict) -> set[str]:
    """Package ids in the resolved graph below the binary we ship."""
    resolve = meta["resolve"]
    by_id = {p["id"]: p for p in meta["packages"]}
    root = next(i for i, p in by_id.items() if p["name"] == BIN)
    nodes = {n["id"]: n for n in resolve["nodes"]}
    seen: set[str] = set()
    stack = [root]
    while stack:
        node = stack.pop()
        if node in seen:
            continue
        seen.add(node)
        stack.extend(d["pkg"] for d in nodes[node]["deps"])
    return seen


def registry_text(pkg: dict) -> str | None:
    """Licence file from the extracted crate source, if cargo kept one."""
    for base in (Path.home() / ".cargo" / "registry" / "src").glob("*"):
        d = base / f"{pkg['name']}-{pkg['version']}"
        if not d.is_dir():
            continue
        for name in sorted(d.iterdir()):
            if not name.name.lower().startswith(("license", "licence", "copying")):
                continue
            if name.is_file() and name.stat().st_size < 200_000:
                text = name.read_text(encoding="utf-8", errors="replace")
                if len(text.strip()) > 200:
                    return f"{name.name}\n{'-' * len(name.name)}\n\n{text.rstrip()}"
    return None


def fallback_text(pkg: dict) -> str | None:
    """Canonical text for a recognised SPDX id when the crate ships none."""
    spdx = pkg.get("license") or ""
    for ident, path in CANONICAL.items():
        if ident in spdx and path.is_file():
            return (f"{path.name} (canonical text, crate ships none)\n"
                    f"{'-' * 40}\n\n{path.read_text(encoding='utf-8').rstrip()}")
    return None


def main() -> int:
    meta = metadata()
    keep = reachable(meta)
    members = {p["name"] for p in meta["packages"]
               if p.get("source") is None
               and p["name"].startswith(("z2m-guard", "guard-"))}
    pkgs = sorted((p for p in meta["packages"] if p["id"] in keep),
                  key=lambda p: (p["name"], p["version"]))

    rows, absent = [], []
    for p in pkgs:
        if p["name"] in members:
            continue
        text = registry_text(p)
        if text is None:
            text = fallback_text(p)
            if text is None:
                absent.append(p["name"])
        rows.append((p, text))

    md = [
        "# Third-party licences",
        "",
        f"`{BIN}` links {len(rows)} third-party crates for `{TARGET}`. All of them",
        "are permissive; no copyleft dependency is involved. Generated by",
        "`scripts/license-notices.py` — do not edit by hand.",
        "",
        "Verbatim licence texts are bundled with each release artifact as",
        "`THIRD-PARTY-LICENSES.txt`, one section per crate.",
        "",
        "| Crate | Version | Licence |",
        "|---|---|---|",
    ]
    md += [f"| `{p['name']}` | {p['version']} | {p.get('license') or '—'} |" for p, _ in rows]
    if absent:
        md += ["", "For these crates neither a licence file nor a canonical text was "
               "available; the SPDX identifier in the table applies: "
               + ", ".join(f"`{n}`" for n in absent)]
    OUT_MD.write_text("\n".join(md) + "\n", encoding="utf-8")

    txt = [
        f"THIRD-PARTY LICENCES FOR {BIN}",
        "=" * 40,
        "",
        f"{BIN} itself is licensed under MIT OR Apache-2.0 (see LICENSE-MIT and",
        "LICENSE-APACHE, both shipped alongside this file). The components below",
        "are compiled into the distributed binary and are reproduced here to",
        "satisfy their attribution terms.",
        "",
    ]
    for p, text in rows:
        txt += ["=" * 78,
                f"{p['name']} {p['version']}  —  {p.get('license') or 'see text'}",
                *([f"source: {p['repository']}"] if p.get("repository") else []),
                "=" * 78, ""]
        txt.append(text if text else
                   "No licence text was shipped in the crate source; the SPDX "
                   "identifier above applies.")
        txt.append("")
    OUT_TXT.parent.mkdir(parents=True, exist_ok=True)
    OUT_TXT.write_text("\n".join(txt) + "\n", encoding="utf-8")

    print(f"{OUT_MD.relative_to(ROOT)}: {len(rows)} third-party crates")
    print(f"{OUT_TXT.relative_to(ROOT)}: {OUT_TXT.stat().st_size // 1024} KiB")
    if absent:
        print("without any text:", ", ".join(absent))
    return 0


if __name__ == "__main__":
    sys.exit(main())